(() => {
  const button = document.querySelector('.language-toggle');
  const textEntries = [];
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement.closest('script, style, .language-toggle') && node.textContent.trim()) textEntries.push([node, node.textContent]);
  }
  const attributes = [];
  document.querySelectorAll('[aria-label], [alt], meta[name="description"]').forEach(el => {
    for (const attr of ['aria-label', 'alt', 'content']) {
      if (el.hasAttribute(attr) && el.getAttribute(attr)) attributes.push([el, attr, el.getAttribute(attr)]);
    }
  });
  function translate(text) {
    const trimmed = text.trim();
    if (slTranslations[trimmed]) return text.replace(trimmed, slTranslations[trimmed]);
    return text
      .replace(/^(\d+ \/ )commissions$/, '$1naročila')
      .replace(/^(\d+ \/ )portraits$/, '$1portreti')
      .replace(/^Enlarge (.+) photograph (\d+)$/, 'Povečaj fotografijo $2 — $1')
      .replace(/ — photograph (\d+)$/, ' — fotografija $1')
      .replace(/ photographs$/, ' — fotografije')
      .replace(/ credits$/, ' — sodelujoči');
  }
  let language = 'en';
  try { language = localStorage.getItem('luka00-language') === 'sl' ? 'sl' : 'en'; } catch {}
  function apply() {
    document.documentElement.lang = language;
    textEntries.forEach(([node, original]) => { node.textContent = language === 'sl' ? translate(original) : original; });
    attributes.forEach(([el, attr, original]) => el.setAttribute(attr, language === 'sl' ? translate(original) : original));
    button.querySelector('[data-language="en"]').classList.toggle('active', language === 'en');
    button.querySelector('[data-language="sl"]').classList.toggle('active', language === 'sl');
    button.setAttribute('aria-label', language === 'en' ? 'Preklopi v slovenščino' : 'Switch to English');
    try { localStorage.setItem('luka00-language', language); } catch {}
  }
  button.addEventListener('click', () => { language = language === 'en' ? 'sl' : 'en'; apply(); });
  apply();
})();
